/// Corner radius scale. Pick by role, not by eye.
abstract final class AppRadii {
  /// Small controls: badges, thumbnails, progress bars.
  static const double sm = 8;

  /// Inputs, tiles inside a card, compact surfaces.
  static const double md = 14;

  /// Cards, grouped lists, dialogs.
  static const double lg = 20;

  /// Media cards — photos and the Discover card.
  static const double card = 24;

  /// Bottom sheets and full-bleed hero surfaces.
  static const double xl = 28;

  /// Buttons, chips, pills.
  static const double pill = 999;
}
